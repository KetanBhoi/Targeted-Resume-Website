type Dict = Record<string, string>;
const hi: Dict = {};
const gu: Dict = {};
for (const [en, h, g] of translationEntries) {
  hi[en] = h;
  gu[en] = g;
}
export const dictionaries: Record<'hi' | 'gu', Dict> = { hi, gu };

export function translate(language: PortfolioLanguage, english: string): string {
  if (language === 'en') return english;
  return dictionaries[language][english] ?? english;
}

export type LocalizedPortfolio = typeof portfolio;

/** Typed localized copy of the portfolio. Names, companies, dates, credentials, URLs and tool names are untouched. */
export function localizePortfolio(language: PortfolioLanguage): LocalizedPortfolio {
  if (language === 'en') return portfolio;
  const t = (s: string) => translate(language, s);
  return {
    ...portfolio,
    targetRole: t(portfolio.targetRole),
    positioning: t(portfolio.positioning),
    context: t(portfolio.context),
    strengths: portfolio.strengths.map((s) => ({ ...s, title: t(s.title), detail: t(s.detail), proof: t(s.proof) })),
    experiences: portfolio.experiences.map((e) => ({ ...e, bullets: e.bullets.map(t) })),
    projects: portfolio.projects.map((p) => ({
      ...p, name: t(p.name), kind: t(p.kind), context: t(p.context), problem: t(p.problem), contribution: t(p.contribution), outcome: t(p.outcome),
    })),
    skills: portfolio.skills.map((g) => ({ group: t(g.group), items: g.items.map(t) })),
    softSkills: portfolio.softSkills.map(t),
    publicContact: portfolio.publicContact ? { ...portfolio.publicContact, label: t(portfolio.publicContact.label) } : null,
  };
}
